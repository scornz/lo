const BOT: &str = "rozed-bot";

/// The tab signed in as the test bot, with its poller and the database where it records
/// viewed files.
struct SignedIn {
    /// GitHub, which answers the viewed-mark mutations as each test says, and every other request
    /// as if it were down, so the poller's polls change nothing and it doesn't think it's offline.
    github: FakeGithub,
    records: ViewedRecords,
    pull: PullRef,
    accounts: Entity<github::accounts::Accounts>,
    cache: github::cache::PrCache,
    /// The account's poller, which Lo's GitHub layer keeps after its tabs close.
    _poller: Entity<Poller>,
}

/// Signs `tab` in as the bot, with `recorded` already in its records of viewed files.
async fn sign_in_bot(
    tab: &Entity<PrTab>,
    name: &str,
    recorded: &[(&str, &str)],
    cx: &mut VisualTestContext,
) -> SignedIn {
    let github = FakeGithub::default();
    github.answer_unhandled(Answer::new(503, "{}"));
    github.answer_viewed_marks();
    let db = github::db::LoDb::open_test(name).await;
    let store =
        std::sync::Arc::new(credentials_provider::test_support::FakeCredentialsProvider::default());
    let accounts = cx
        .update(|_, cx| {
            let http = std::sync::Arc::new(github.clone());
            github::accounts::Accounts::load(db.clone(), store, http, cx)
        })
        .unwrap();
    let user = github::AuthenticatedUser {
        user: github::User {
            login: BOT.into(),
            id: 353226052,
            name: None,
            avatar_url: None,
        },
        scopes: vec!["repo".into()],
    };
    accounts
        .update(cx, |accounts, cx| {
            accounts.add(
                user,
                github::Token::new("gho_FAKE"),
                github::db::AccountSource::DeviceFlow,
                cx,
            )
        })
        .await
        .unwrap();
    let records = ViewedRecords::new(db.clone());
    let pull = PullRef::new("rozed-dev", "playground", 2);
    for (path, head) in recorded {
        records
            .record(BOT, &pull, path, head, SystemTime::now())
            .await
            .unwrap();
    }
    let cache = github::cache::PrCache::new(db);
    let poller = cx.new(|cx| {
        Poller::new(
            accounts.clone(),
            BOT,
            cache.clone(),
            github::poll::PollConfig::default(),
            cx,
        )
    });
    tab.update(cx, |tab, cx| {
        tab.set_acting(Acting::Account(BOT.into()), cx);
        tab.watch(poller.clone(), pull.clone(), Some(records.clone()), cx);
    });
    cx.run_until_parked();
    SignedIn {
        _poller: poller,
        github,
        records,
        pull,
        accounts,
        cache,
    }
}

impl SignedIn {
    fn recorded(&self) -> HashMap<String, String> {
        self.records.heads(BOT, &self.pull).unwrap()
    }
}

