//! The store keeps each blob's symbols, so a commit reads only the blobs it changed.

use std::convert::Infallible;

use symbol_index::{BlobId, File, Limits, Skip, Store};

use crate::support::{Blobs, names};

#[test]
fn a_commit_reads_only_the_blobs_it_changed() {
    let blobs = Blobs::default();
    let mut store = Store::default();

    let first = blobs.commit(&[
        ("src/a.rs", "fn a() {}"),
        ("src/b.rs", "fn b() {}"),
        ("src/c.rs", "fn c() {}"),
    ]);
    store.index(&first, |file| blobs.read(file)).unwrap();
    assert_eq!(blobs.take_reads(), ["src/a.rs", "src/b.rs", "src/c.rs"]);

    // b.rs changes, and c.rs moves.
    let second = blobs.commit(&[
        ("src/a.rs", "fn a() {}"),
        ("src/b.rs", "fn b() {}\nfn b2() {}"),
        ("src/moved/c.rs", "fn c() {}"),
    ]);
    let index = store.index(&second, |file| blobs.read(file)).unwrap();

    assert_eq!(blobs.take_reads(), ["src/b.rs"]);
    assert_eq!(names(&index, "src/a.rs"), ["a"]);
    assert_eq!(names(&index, "src/b.rs"), ["b", "b2"]);
    assert_eq!(names(&index, "src/moved/c.rs"), ["c"]);
    assert!(index.symbols_in("src/c.rs").is_none());
}

#[test]
fn a_blob_at_two_paths_is_read_once() {
    let blobs = Blobs::default();
    let files = blobs.commit(&[("a/lib.rs", "fn same() {}"), ("b/lib.rs", "fn same() {}")]);

    let index = Store::default()
        .index(&files, |file| blobs.read(file))
        .unwrap();

    assert_eq!(blobs.take_reads().len(), 1);
    assert_eq!(names(&index, "a/lib.rs"), ["same"]);
    assert_eq!(names(&index, "b/lib.rs"), ["same"]);
}

#[test]
fn a_blob_is_read_again_for_another_grammar() {
    // Every empty file has the same blob.
    let blobs = Blobs::default();
    let files = blobs.commit(&[("empty.py", ""), ("empty.rs", "")]);

    Store::default()
        .index(&files, |file| blobs.read(file))
        .unwrap();

    assert_eq!(blobs.take_reads(), ["empty.py", "empty.rs"]);
}

#[test]
fn missing_lists_each_blob_still_to_read_once() {
    let blobs = Blobs::default();
    let mut store = Store::default();
    store
        .index(&blobs.commit(&[("old.rs", "fn old() {}")]), |file| {
            blobs.read(file)
        })
        .unwrap();

    let files = blobs.commit(&[
        ("old.rs", "fn old() {}"),
        ("new.rs", "fn new() {}"),
        ("copy.rs", "fn new() {}"),
    ]);
    let missing: Vec<&str> = store
        .missing(&files)
        .into_iter()
        .map(|file| file.path.as_str())
        .collect();

    assert_eq!(missing, ["new.rs"]);
}

#[test]
fn a_file_over_the_size_limit_is_skipped_unread() {
    let blobs = Blobs::default();
    let mut store = Store::new(Limits { max_file_size: 20 });
    let files = blobs.commit(&[
        ("small.rs", "fn small() {}"),
        ("large.rs", "fn large() { /* longer than 20 bytes */ }"),
    ]);

    assert_eq!(store.missing(&files).len(), 1);
    let index = store.index(&files, |file| blobs.read(file)).unwrap();

    assert_eq!(blobs.take_reads(), ["small.rs"]);
    assert_eq!(index.skipped("large.rs"), Some(Skip::TooLarge));
    assert!(index.symbols_in("large.rs").is_none());
    assert_eq!(index.skipped("small.rs"), None);
}

#[test]
fn contents_larger_than_their_listed_size_are_skipped_once_read() {
    let blobs = Blobs::default();
    let mut store = Store::new(Limits { max_file_size: 20 });
    let mut file = blobs.file("large.rs", "fn large() { /* longer than 20 bytes */ }");
    file.size = 10;

    let index = store
        .index(std::slice::from_ref(&file), |file| blobs.read(file))
        .unwrap();
    assert_eq!(index.skipped("large.rs"), Some(Skip::TooLarge));

    // It isn't read again.
    store
        .index(std::slice::from_ref(&file), |file| blobs.read(file))
        .unwrap();
    assert_eq!(blobs.take_reads(), ["large.rs"]);
}

#[test]
fn generated_files_are_skipped() {
    let blobs = Blobs::default();
    let mut store = Store::default();
    let minified = format!("function a(){{{}}}\n", "var b=1;".repeat(500));
    let mut files = blobs.commit(&[
        (
            "api.go",
            "// Code generated by protoc-gen-go. DO NOT EDIT.\n\npackage api\n\nfunc Get() {}\n",
        ),
        ("schema.rs", "// @generated by diesel\n\nfn table() {}\n"),
        (
            "bindings.rs",
            "/* automatically generated by rust-bindgen */\n\nfn ffi() {}\n",
        ),
        ("dist/app.js", &minified),
        ("vendor/lib.min.js", "function a(){}"),
        ("marked.ts", "export function marked() {}"),
        (
            "handwritten.rs",
            "// Not generated: do edit this file.\nfn handwritten() {}\n",
        ),
    ]);
    // `.gitattributes` marks it `linguist-generated`.
    files[5].generated = true;

    let index = store.index(&files, |file| blobs.read(file)).unwrap();

    for path in [
        "api.go",
        "schema.rs",
        "bindings.rs",
        "dist/app.js",
        "vendor/lib.min.js",
        "marked.ts",
    ] {
        assert_eq!(index.skipped(path), Some(Skip::Generated), "{path}");
    }
    assert_eq!(names(&index, "handwritten.rs"), ["handwritten"]);
    // Neither the minified path nor the marked file was read.
    assert_eq!(
        blobs.take_reads(),
        [
            "api.go",
            "bindings.rs",
            "dist/app.js",
            "handwritten.rs",
            "schema.rs"
        ]
    );

    // Files found generated by their contents aren't read again.
    store.index(&files, |file| blobs.read(file)).unwrap();
    assert!(blobs.take_reads().is_empty());
}

#[test]
fn a_failed_read_keeps_the_blobs_already_read() {
    let blobs = Blobs::default();
    let mut store = Store::default();
    let files = blobs.commit(&[("a.rs", "fn a() {}"), ("b.rs", "fn b() {}")]);

    let result = store.index(&files, |file| {
        if file.path == "b.rs" {
            Err("b.rs is gone")
        } else {
            Ok(blobs.read(file).unwrap())
        }
    });
    assert_eq!(result.err(), Some("b.rs is gone"));

    let index = store.index(&files, |file| blobs.read(file)).unwrap();
    assert_eq!(names(&index, "a.rs"), ["a"]);
    assert_eq!(names(&index, "b.rs"), ["b"]);
    // a.rs is read by the first try, unless b.rs failed before its turn, or by the second: never
    // both.
    assert_eq!(blobs.take_reads(), ["a.rs", "b.rs"]);
}

#[test]
fn blob_ids_compare_by_their_text() {
    let id = BlobId::from("e69de29bb2d1d6434b8b29ae775ad8c2e48c5391");

    assert_eq!(id, BlobId::from(String::from(id.as_str())));
    assert_eq!(id.to_string(), "e69de29bb2d1d6434b8b29ae775ad8c2e48c5391");
}

#[test]
fn an_empty_commit_has_an_empty_index() {
    let files: [File<'static>; 0] = [];
    let index = Store::default()
        .index(&files, |_| -> Result<Vec<u8>, Infallible> {
            unreachable!()
        })
        .unwrap();

    assert!(index.symbols_in("anything.rs").is_none());
}
